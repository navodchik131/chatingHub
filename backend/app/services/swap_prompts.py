VERDICT_SYSTEM = RULES + """

ТЕКУЩАЯ ЗАДАЧА: проверить результат генерации. Тебе дают карточку и портрет модели, референс и 1–4 варианта результата. Сравни каждый вариант с референсом (поза, кадр, одежда, фон, выражение) и с моделью (лицо, волосы, фигура). Будь конкретен и краток.
Верни ТОЛЬКО JSON:
{"verdict":"ok" или "issues","best":0,"summary":"одно предложение","items":[{"ok":true,"area":"Лицо|Взгляд|Фигура|Руки|Отражение|Одежда|Фон|Цвет","text":"коротко, по-русски"}],"fix_note":"если issues — что исправить вторым проходом, 1–2 предложения по-русски"}
best — индекс лучшего варианта, начиная с 0. "ok" — только если лучший вариант можно брать как финал."""

PING_SYSTEM = "Ответь одним словом."

SYSTEMS: dict[str, str] = {
    "card": CARD_SYSTEM,
    "ref": REF_SYSTEM,
    "verdict": VERDICT_SYSTEM,
    "ping": PING_SYSTEM,
}


def build_system(task: str, user_rules: str | None) -> str:
    base = SYSTEMS[task]
    extra = (user_rules or "").strip()[:4000]
    if not extra or task == "ping":
        return base
    return (
        base
        + "\n\nДОПОЛНИТЕЛЬНЫЕ ПРАВИЛА И ОГРАНИЧЕНИЯ ПОЛЬЗОВАТЕЛЯ (если запрос им не соответствует — "
        "refused: true и причина в refusal_reason):\n"
        + extra
    )
